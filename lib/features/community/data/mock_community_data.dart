  /// Get top rated contributions (upvotes > 100)
  static List<CommunityContribution> getTopRated() {
    return generateMockContributions()
        .where((c) => c.upvotes > 100 && c.status == ContributionStatus.approved)
        .toList()
      ..sort((a, b) => b.upvotes.compareTo(a.upvotes));
  }

  /// Get trending contributions (recent + high engagement)
  static List<CommunityContribution> getTrending() {
    final now = DateTime.now();
    return generateMockContributions()
        .where((c) =>
            c.status == ContributionStatus.approved &&
            c.createdAt.isAfter(now.subtract(const Duration(days: 30))))
        .toList()
      ..sort((a, b) {
        final scoreA = a.upvotes + a.saves;
        final scoreB = b.upvotes + b.saves;
        return scoreB.compareTo(scoreA);
      });
  }
