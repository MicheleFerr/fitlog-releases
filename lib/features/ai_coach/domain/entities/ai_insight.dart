import 'package:freezed_annotation/freezed_annotation.dart';

part 'ai_insight.freezed.dart';
part 'ai_insight.g.dart';

/// Represents an AI-generated coaching insight
@freezed
abstract class AIInsight with _$AIInsight {
  const factory AIInsight({
    required String id,
    required InsightType type,
    required InsightSeverity severity,
    required String title,
    required String description,
    required String recommendation,
    required int priority,
    String? affectedExercise,
    List<String>? affectedTemplates,
    List<String>? scientificStrategies,
    Map<String, dynamic>? dataPoints,
    required DateTime timestamp,
  }) = _AIInsight;

  factory AIInsight.fromJson(Map<String, dynamic> json) =>
      _$AIInsightFromJson(json);
}

/// Type of insight generated by the AI Coach
enum InsightType {
  muscleGroupBalance,
  progressOverload,
  recoveryPattern,
  volumeOptimization,
  frequencyRecommendation,
  plateauBreaker,
  formWarning,
  motivational,
  // New analyzer types (addressing blind spots)
  cnsFatigue,
  periodization,
  mobility,
}

/// Severity level of the insight
enum InsightSeverity {
  low,    // Informational - no immediate action needed
  medium, // Warning - consider action
  high,   // Important - action recommended
  critical, // Urgent - immediate action required
}
